-- Exécuté en SYSDBA : création de l'utilisateur applicatif dans la PDB
ALTER SESSION SET CONTAINER = FREEPDB1;
BEGIN EXECUTE IMMEDIATE 'DROP USER tuning CASCADE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
CREATE USER tuning IDENTIFIED BY Tuning123 QUOTA UNLIMITED ON users DEFAULT TABLESPACE users;
GRANT CREATE SESSION, CREATE TABLE, CREATE PROCEDURE, CREATE SEQUENCE, CREATE VIEW TO tuning;
GRANT SELECT ANY DICTIONARY TO tuning;
GRANT EXECUTE ON dbms_stats TO tuning;
EXIT
